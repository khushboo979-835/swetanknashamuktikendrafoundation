<!-- Initialization script in vanilla JS -->
<script>
    document.addEventListener('DOMContentLoaded', function () {
        const testimonialsSwiper = new Swiper('.testimonialsSwiper', {
            loop: true,
            centeredSlides: true,
            speed: 600,
            grabCursor: true, // Shows hand icon to indicate scroll/swipe
            autoplay: {
                delay: 2500, // Faster automatic sliding
                disableOnInteraction: false
            },
            breakpoints: {
                0: { slidesPerView: 1, spaceBetween: 12 },
                768: { slidesPerView: 2, spaceBetween: 20 },
                1170: { slidesPerView: 3, spaceBetween: 30 }
            },
            pagination: {
                el: '.testimonials-pagination',
                clickable: true
            },
            navigation: {
                nextEl: '.swiper-button-next',
                prevEl: '.swiper-button-prev'
            }
        });

        // Pause autoplay on hover (better UX)
        const swiperEl = document.querySelector('.testimonialsSwiper');
        if (swiperEl) {
            swiperEl.addEventListener('mouseenter', () => testimonialsSwiper.autoplay.stop());
            swiperEl.addEventListener('mouseleave', () => testimonialsSwiper.autoplay.start());
            
            // For touch devices (mobile swipe)
            swiperEl.addEventListener('touchstart', () => testimonialsSwiper.autoplay.stop());
            swiperEl.addEventListener('touchend', () => testimonialsSwiper.autoplay.start());
        }
    });
</script>